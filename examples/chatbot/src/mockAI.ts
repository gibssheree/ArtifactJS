import type { ArtifactDefinition, ArtifactPatch } from "@interactive-artifact/protocol";
import { PatchBuilder } from "@interactive-artifact/ai";

export interface MockAIResponse {
  message: string;
  artifact?: ArtifactDefinition;
  patch?: ArtifactPatch;
}

export function generateMockAIResponse(
  userText: string,
  existingArtifact: ArtifactDefinition | null
): MockAIResponse {
  const lower = userText.toLowerCase();

  // 1. Initial Architecture Creation
  if (
    lower.includes("create") ||
    lower.includes("architecture") ||
    lower.includes("diagram") ||
    !existingArtifact
  ) {
    const artifact: ArtifactDefinition = {
      version: "1.0",
      id: "artifact_chatbot_arch",
      type: "diagram.flowchart",
      metadata: {
        title: "React + Laravel + MySQL Architecture",
        description: "Generated by AI Assistant"
      },
      canvas: {
        width: 850,
        height: 480,
        theme: "neutral",
        grid: true
      },
      elements: [
        {
          id: "react_frontend",
          type: "node",
          position: { x: 80, y: 180 },
          size: { width: 170, height: 75 },
          props: {
            label: "React Frontend",
            subLabel: "Vite + Tailwind",
            shape: "rectangle",
            status: "active"
          },
          style: {
            fill: "#eff6ff",
            stroke: "#3b82f6",
            strokeWidth: 2,
            radius: 12
          }
        },
        {
          id: "laravel_api",
          type: "node",
          position: { x: 360, y: 180 },
          size: { width: 170, height: 75 },
          props: {
            label: "Laravel API",
            subLabel: "PHP 8.3 REST",
            shape: "rectangle",
            status: "success"
          },
          style: {
            fill: "#fff1f2",
            stroke: "#f43f5e",
            strokeWidth: 2,
            radius: 12
          }
        },
        {
          id: "mysql_db",
          type: "node",
          position: { x: 640, y: 175 },
          size: { width: 160, height: 85 },
          props: {
            label: "MySQL Database",
            subLabel: "InnoDB Storage",
            shape: "cylinder",
            status: "active"
          },
          style: {
            fill: "#fefce8",
            stroke: "#eab308",
            strokeWidth: 2
          }
        }
      ],
      connections: [
        {
          id: "conn_react_laravel",
          from: "react_frontend",
          to: "laravel_api",
          type: "arrow",
          label: "JSON / REST",
          style: { stroke: "#3b82f6", strokeWidth: 2 }
        },
        {
          id: "conn_laravel_mysql",
          from: "laravel_api",
          to: "mysql_db",
          type: "arrow",
          label: "PDO / SQL",
          style: { stroke: "#f43f5e", strokeWidth: 2 }
        }
      ],
      interactions: []
    };

    return {
      message: "Here is the architecture diagram for your React frontend, Laravel API, and MySQL database. You can pan, zoom, and drag elements interactively!",
      artifact
    };
  }

  // 2. Move MySQL underneath API
  if (lower.includes("underneath") || lower.includes("under") || (lower.includes("move") && lower.includes("mysql"))) {
    return {
      message: "I've applied an incremental patch to move the MySQL database directly underneath the Laravel API. The connection arrow automatically recalculated its geometry!",
      patch: PatchBuilder.move("mysql_db", 360, 320)
    };
  }

  // 3. Add Redis cache
  if (lower.includes("redis") || lower.includes("cache")) {
    const patch = PatchBuilder.batch([
      PatchBuilder.insert({
        id: "redis_cache",
        type: "node",
        position: { x: 640, y: 180 },
        size: { width: 160, height: 75 },
        props: {
          label: "Redis Cache",
          subLabel: "Session & Query Cache",
          shape: "pill",
          status: "active"
        },
        style: {
          fill: "#fef2f2",
          stroke: "#dc2626",
          strokeWidth: 2
        }
      }),
      PatchBuilder.connect({
        id: "conn_laravel_redis",
        from: "laravel_api",
        to: "redis_cache",
        type: "arrow",
        label: "RESP / Cache",
        style: { stroke: "#dc2626", strokeWidth: 2 }
      })
    ]);

    return {
      message: "I've patched the diagram to insert a Redis Cache node alongside a direct connection from the Laravel API.",
      patch
    };
  }

  // Default fallback update
  return {
    message: `I received your instruction: "${userText}". Try asking: "Move MySQL underneath the API" or "Add a Redis cache"!`
  };
}
